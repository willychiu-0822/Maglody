test('UAT-38 A-02 儲存失敗時保留草稿並明示未存',async({page},info)=>{
  const originalSetItem = await page.evaluateHandle(() => Storage.prototype.setItem)
  await page.evaluate(()=>{ Storage.prototype.setItem = ()=>{throw new DOMException('full','QuotaExceededError')} })
  await visit(page,'構想')
  await page.locator('.mood').first().click()
  await expect(page.locator('.storage-notice')).toContainText('還沒存')
  await page.getByRole('button',{name:'記一下靈感',exact:true}).click()
  await page.getByRole('textbox',{name:'靈感文字'}).fill('不能丟的字')
  await page.getByRole('button',{name:'夾進本子',exact:true}).click()
  await expect(page.getByRole('textbox',{name:'靈感文字'})).toHaveValue('不能丟的字')
  await expect(page.locator('.toast')).toContainText('還沒存好')
  await shot(page,'A02',info.project.name)
  await page.getByRole('button',{name:'好',exact:true}).click()
  await page.getByRole('button',{name:'關閉',exact:true}).click()
  await page.evaluate(fn => { Storage.prototype.setItem = fn }, originalSetItem)
  await originalSetItem.dispose()
  await page.getByRole('button',{name:'重試保存',exact:true}).click()
  await expect(page.locator('.storage-notice')).toHaveCount(0)
  await page.reload()
  await visit(page,'構想')
  await expect(page.locator('.mood').first()).toHaveAttribute('aria-pressed','true')
})
