test('UAT-65 工作室手記隨自己的創作長出素材，跳檯與重整仍看得到', async ({ page }, info) => {
  await setup(page)
  const room = page.locator('.studio-presence')
  const paper = page.getByRole('region', { name: '哼唱解析創作紙頁' })
  const roomBox = await room.boundingBox()
  const paperBox = await paper.boundingBox()
  expect(roomBox!.height, '人物應在清楚可見的場景中').toBeGreaterThanOrEqual(220)
  if (info.project.name === 'desktop') expect(paperBox!.x).toBeGreaterThan(roomBox!.x + roomBox!.width)
  else expect(paperBox!.y).toBeGreaterThan(roomBox!.y + roomBox!.height)
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(0)
  await go(page, '構想')
  await primary(page).click()
  await page.getByRole('textbox', { name: '這首歌的一句話' }).fill('晚風帶我回家')
  await expect(page.getByLabel('歌曲手記')).toContainText('《晚風帶我回家》的手記')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveText(['✓ 一句靈感已留下'])
  await go(page, '歌詞')
  await page.locator('.lyric-input').fill('晚風在窗邊等我')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(2)
  await page.reload()
  await go(page, '歌詞')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(2)
  await expect(page.locator('.lyric-input')).toHaveValue('晚風在窗邊等我')
  await expect(primary(page)).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

