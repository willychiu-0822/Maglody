import { test, expect, setup, go, primary } from './helpers'

test('UAT-65 工作室手記隨自己的創作長出素材，跳檯與重整仍看得到', async ({ page }, info) => {
  await setup(page)
  const room = page.locator('.studio-presence')
  const paper = page.getByRole('region', { name: '哼唱解析創作紙頁' })
  const roomBox = await room.boundingBox()
  const paperBox = await paper.boundingBox()
  expect(roomBox!.height, '人物應在清楚可見的場景中').toBeGreaterThanOrEqual(220)
  if (info.project.name === 'desktop') expect(paperBox!.x).toBeGreaterThan(roomBox!.x + roomBox!.width)
  else expect(paperBox!.y).toBeGreaterThan(roomBox!.y + roomBox!.height)
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(0)
  await go(page, '構想')
  await primary(page).click()
  await page.getByRole('textbox', { name: '這首歌的一句話' }).fill('晚風帶我回家')
  await expect(page.getByLabel('歌曲手記')).toContainText('《晚風帶我回家》的手記')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveText(['✓ 一句靈感已留下'])
  await go(page, '歌詞')
  await page.locator('.lyric-input').fill('晚風在窗邊等我')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(2)
  await page.reload()
  await go(page, '歌詞')
  await expect(page.locator('.song-trail li[data-kept="true"]')).toHaveCount(2)
  await expect(page.locator('.lyric-input')).toHaveValue('晚風在窗邊等我')
  await expect(primary(page)).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('UAT-66 創作地圖標記目前工作檯，能自由拜訪並帶著作品回來', async ({ page }, info) => {
  await setup(page)
  await page.getByRole('button', { name: '打開工作室選單' }).click()
  const map = page.getByRole('navigation', { name: '創作地圖' })
  await expect(map).toBeVisible()
  await expect(map.locator('[aria-current="location"]')).toHaveCount(1)
  await expect(map.locator('[aria-current="location"]')).toContainText('哼唱解析')
  await expect(map.locator('.menu-desk')).toHaveCount(9)
  await expect(map.getByRole('button', { name: /歌詞/ })).toBeEnabled()
  await expect(map).toContainText('可以跳著走，隨時回來')
  const imgs = map.locator('img')
  await expect(imgs).toHaveCount(9)
  await expect.poll(() => imgs.evaluateAll(es => es.every(e => (e as HTMLImageElement).complete && (e as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await page.screenshot({ path: `docs/uat/evidence/A-UI-04-map-${info.project.name}.png`, animations: 'disabled' })
  await map.getByRole('button', { name: /歌詞/ }).click()
  await page.locator('.lyric-input').fill('地圖的另一邊，也能開始寫歌')
  await page.reload()
  await go(page, '歌詞')
  await expect(page.locator('.lyric-input')).toHaveValue('地圖的另一邊，也能開始寫歌')
  await page.getByRole('button', { name: '打開工作室選單' }).click()
  await expect(map.locator('[aria-current="location"]')).toHaveCount(1)
  await expect(map.locator('[aria-current="location"]')).toContainText('歌詞')
  await page.getByRole('button', { name: '✎ 記一下', exact: true }).click()
  await page.locator('.inspo-capture textarea').fill('在地圖裡想到的新詞')
  await page.getByRole('button', { name: '夾進本子', exact: true }).click()
  await expect(map).toBeVisible()
  await expect(page.getByRole('dialog', { name: '工作室', exact: true }).locator('.menu-more')).not.toHaveAttribute('open', '')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

