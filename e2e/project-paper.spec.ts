import { test, expect, setup, finished, go, primary, readProject, captureText, library } from './helpers'

async function openVersions(page: import('@playwright/test').Page) {
  await page.getByRole('button', { name: '打開工作室選單' }).click()
  await page.locator('.menu-more > summary').click()
}
async function paperCheck(page: import('@playwright/test').Page, name: string) {
  const dialog = page.getByRole('dialog', { name, exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.primary-action')).toHaveCount(1)
  const undersized = await dialog.locator('button').evaluateAll(es => es.filter(e => e.checkVisibility()).filter(e => { const b = e.getBoundingClientRect(); return b.width < 44 || b.height < 44 }).length)
  expect(undersized).toBe(0)
  await page.mouse.click(2, 2)
  await expect(dialog).toBeVisible()
  return dialog
}

test('UAT-76 保存、還原與新歌使用紙頁明確確認，取消不改稿', async ({ page }, info) => {
  // A missing confirmation, premature restore/reset or missing version write must fail this journey.
  const native: string[] = []
  page.on('dialog', d => { native.push(d.message()); void d.dismiss() })
  await setup(page, finished)
  await captureText(page, '新歌仍要帶著這則靈感')
  await page.getByRole('button', { name: '好', exact: true }).click()
  await openVersions(page)
  const opener = page.getByRole('button', { name: '存成新的一版', exact: true })
  await opener.click()
  let dialog = await paperCheck(page, '留住這一版')
  await expect(dialog).toContainText('鑰匙留在門口')
  await dialog.getByRole('textbox', { name: '這一版的說明（選填）' }).fill('先保留雨聲的版本')
  await page.screenshot({ path: `docs/uat/evidence/A-UI-15-save-${info.project.name}.png`, animations: 'disabled' })
  await dialog.locator('.primary-action').click()
  await expect(dialog).toContainText('存好了：Demo v1')
  await expect(page.locator('.version')).toContainText('先保留雨聲的版本')
  await dialog.getByRole('button', { name: '好，回到工作室', exact: true }).click()
  await expect(opener).toBeFocused()
  await page.getByRole('dialog', { name: '工作室', exact: true }).getByRole('button', { name: '關閉', exact: true }).click()
  await go(page, '構想')
  await page.locator('.one-line').fill('我改過的新句子')
  await openVersions(page)
  const restore = page.getByRole('button', { name: '回到這版', exact: true })
  await restore.click()
  dialog = await paperCheck(page, '回到這一版')
  await expect(dialog).toContainText('Demo v1')
  await page.screenshot({ path: `docs/uat/evidence/A-UI-15-restore-${info.project.name}.png`, animations: 'disabled' })
  await dialog.getByRole('button', { name: '先不換', exact: true }).click()
  expect((await readProject(page)).idea.hook).toBe('我改過的新句子')
  await expect(restore).toBeFocused()
  await restore.click()
  await page.getByRole('dialog', { name: '回到這一版', exact: true }).locator('.primary-action').click()
  expect((await readProject(page)).idea.hook).toBe('鑰匙留在門口')
  const reset = page.getByRole('button', { name: '重新開始一首新歌', exact: true })
  await reset.click()
  dialog = await paperCheck(page, '翻開新的一頁')
  await page.screenshot({ path: `docs/uat/evidence/A-UI-15-new-${info.project.name}.png`, animations: 'disabled' })
  await dialog.getByRole('button', { name: '繼續這首歌', exact: true }).click()
  expect((await readProject(page)).idea.hook).toBe('鑰匙留在門口')
  await reset.click()
  await page.getByRole('dialog', { name: '翻開新的一頁', exact: true }).locator('.primary-action').click()
  await expect(primary(page)).toHaveText(/哼一段/)
  expect((await readProject(page)).idea.hook).toBe('')
  await library(page)
  await expect(page.locator('.inspo-card').filter({ hasText: '新歌仍要帶著這則靈感' })).toHaveCount(1)
  expect(native).toEqual([])
})

test('UAT-77 版本保存失敗保留說明可重試，捕捉返回與重整不遺失', async ({ page }, info) => {
  // A false success on quota failure, lost note on nested capture, or missing persisted snapshot must fail.
  page.on('dialog', d => { void d.dismiss() })
  await setup(page, finished)
  await openVersions(page)
  await page.getByRole('button', { name: '存成新的一版', exact: true }).click()
  const dialog = await paperCheck(page, '留住這一版')
  const note = '晚風和雨聲'.repeat(100)
  await dialog.getByRole('textbox', { name: '這一版的說明（選填）' }).fill(note)
  await dialog.getByRole('button', { name: '✎ 記一下', exact: true }).click()
  await page.getByRole('textbox', { name: '靈感文字' }).fill('改稿時想到，副歌留一口氣')
  await page.getByRole('button', { name: '夾進本子', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('textbox', { name: '這一版的說明（選填）' })).toHaveValue(note)
  await expect(dialog.getByRole('button', { name: '✎ 記一下', exact: true })).toBeFocused()
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    ;(window as any).__restoreVersionStorage = () => { Storage.prototype.setItem = original }
    Storage.prototype.setItem = function(k, v) { if (k === 'maglody-versions-v1') throw new DOMException('full', 'QuotaExceededError'); return original.call(this, k, v) }
  })
  await dialog.locator('.primary-action').click()
  await expect(dialog.getByRole('status')).toContainText('還沒存好')
  await expect(dialog).not.toContainText('存好了：')
  await expect(page.locator('.version')).toHaveCount(0)
  await expect(dialog.getByRole('textbox', { name: '這一版的說明（選填）' })).toHaveValue(note)
  await page.screenshot({ path: `docs/uat/evidence/A-UI-15-retry-${info.project.name}.png`, animations: 'disabled' })
  await page.evaluate(() => (window as any).__restoreVersionStorage())
  await dialog.getByRole('button', { name: '重試保存', exact: true }).click()
  await expect(dialog).toContainText('存好了：Demo v1')
  await page.screenshot({ path: `docs/uat/evidence/A-UI-15-saved-${info.project.name}.png`, animations: 'disabled' })
  await dialog.getByRole('button', { name: '好，回到工作室', exact: true }).click()
  await page.reload()
  await openVersions(page)
  await expect(page.locator('.version')).toContainText(note)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator('.menu-sheet').evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true)
  const versions = await page.evaluate(() => JSON.parse(localStorage.getItem('maglody-versions-v1')!))
  expect(versions).toHaveLength(1)
  expect(versions[0].project.lyrics[0].text).toBe('雨落在鞋櫃上\n鑰匙安靜發光')
})
